GLYPHS = {}
for _k, _v in _RAW.items():
    GLYPHS[_k] = [[c == "#" for c in row] for row in _v.split("|")]

_CACHE = {}
_CACHE_MAX = 900


def text_width(s, scale=1):
    return len(s) * ADV * scale - scale if s else 0


def _base(s, rgb):
    """Ungeskaltes Text-Bild (ARGB premultiplied)."""
    w = max(1, len(s) * ADV)
    img = QImage(w, GH, QImage.Format.Format_ARGB32_Premultiplied)
    img.fill(0)
    col = QColor(*rgb).rgba()
    for i, ch in enumerate(s.upper()):
        g = GLYPHS.get(ch)
        if g is None:
            if ch == " ":
                continue
            g = GLYPHS["?"]
        ox = i * ADV
        for y, row in enumerate(g):
            for x, on in enumerate(row):
                if on:
                    img.setPixel(ox + x, y, col)
    return img


def render(s, rgb, scale=1, shadow=(4, 5, 10)):
    """Text -> QImage (gecacht). Schatten 1 Skalen-Pixel nach rechts unten."""
    key = (s, tuple(rgb), scale, shadow)
    img = _CACHE.get(key)
    if img is not None:
        return img
    base = _base(s, rgb)
    if scale != 1:
        base = base.scaled(base.width() * scale, base.height() * scale,
                           Qt.AspectRatioMode.IgnoreAspectRatio,
                           Qt.TransformationMode.FastTransformation)
    if shadow is not None:
        sh = _base(s, shadow)
        if scale != 1:
            sh = sh.scaled(sh.width() * scale, sh.height() * scale,
                           Qt.AspectRatioMode.IgnoreAspectRatio,
                           Qt.TransformationMode.FastTransformation)
        out = QImage(base.width() + scale, base.height() + scale,
                     QImage.Format.Format_ARGB32_Premultiplied)
        out.fill(0)
        p = QPainter(out)
        p.drawImage(scale, scale, sh)
        p.drawImage(0, 0, base)
        p.end()
        base = out
    if len(_CACHE) > _CACHE_MAX:
        _CACHE.clear()
    _CACHE[key] = base
    return base


def draw(p, x, y, s, rgb, scale=1, shadow=(4, 5, 10), align="left", opacity=1.0):
    """Text mit QPainter p zeichnen. align: left | center | right. Gibt Breite zurück."""
    if not s:
        return 0
    img = render(s, rgb, scale, shadow)
    w = text_width(s, scale)
    if align == "center":
        x -= w // 2
    elif align == "right":
        x -= w
    if opacity < 1.0:
        p.setOpacity(opacity)
        p.drawImage(int(x), int(y), img)
        p.setOpacity(1.0)
    else:
        p.drawImage(int(x), int(y), img)
    return w
